"""PostgreSQL connection helpers and Phase 2 action persistence."""

from contextlib import contextmanager
import json
from typing import Iterator

import psycopg
from psycopg.rows import dict_row
from psycopg.types.json import Jsonb
from uuid import UUID
from pathlib import Path
from contextvars import ContextVar

request_id_context: ContextVar[str | None] = ContextVar("request_id", default=None)


def json_safe(value):
    """Convert DB-native values such as Decimal and datetime to JSON values."""
    return json.loads(json.dumps(value, default=str))

from app.config import DB_HOST, DB_NAME, DB_PASSWORD, DB_PORT, DB_USER


@contextmanager
def database_connection() -> Iterator[psycopg.Connection]:
    if not DB_PASSWORD:
        raise RuntimeError("POSTGRES_PASSWORD is not configured")
    with psycopg.connect(
        host=DB_HOST,
        port=DB_PORT,
        dbname=DB_NAME,
        user=DB_USER,
        password=DB_PASSWORD,
        connect_timeout=3,
        row_factory=dict_row,
    ) as connection:
        yield connection


def ensure_phase2_tables() -> None:
    """Install additive Phase 2 tables for existing local databases."""
    statements = [
        """CREATE TABLE IF NOT EXISTS shopping_list_items (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            name TEXT NOT NULL,
            quantity NUMERIC(10, 2) NOT NULL DEFAULT 1 CHECK (quantity > 0),
            unit TEXT NOT NULL DEFAULT 'item', is_complete BOOLEAN NOT NULL DEFAULT FALSE,
            created_at TIMESTAMPTZ NOT NULL DEFAULT NOW())""",
        """CREATE TABLE IF NOT EXISTS pending_actions (
            id UUID PRIMARY KEY, tool_name TEXT NOT NULL, arguments JSONB NOT NULL,
            status TEXT NOT NULL DEFAULT 'pending'
                CHECK (status IN ('pending', 'confirmed', 'rejected', 'failed')),
            result JSONB, created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
            expires_at TIMESTAMPTZ NOT NULL DEFAULT NOW() + INTERVAL '15 minutes',
            completed_at TIMESTAMPTZ)""",
        """CREATE TABLE IF NOT EXISTS tool_call_logs (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            tool_name TEXT NOT NULL, arguments JSONB NOT NULL, outcome JSONB NOT NULL,
            latency_ms INTEGER NOT NULL CHECK (latency_ms >= 0),
            created_at TIMESTAMPTZ NOT NULL DEFAULT NOW())""",
    ]
    with database_connection() as connection:
        for statement in statements:
            connection.execute(statement)


def create_pending_action(action_id: str, tool_name: str, arguments: dict) -> None:
    from app.actions import prepare_action
    prepared = prepare_action(tool_name, arguments)
    with database_connection() as connection:
        connection.execute(
            "INSERT INTO pending_actions (id, tool_name, arguments,payload_version,request_id) VALUES (%s,%s,%s,2,%s)",
            (action_id, tool_name, Jsonb(json_safe(prepared)),request_id_context.get()),
        )


def pending_action_expiry(action_id: str) -> str:
    with database_connection() as connection:
        row = connection.execute(
            "SELECT expires_at::text AS expires_at FROM pending_actions WHERE id = %s",
            (UUID(action_id),),
        ).fetchone()
    if row is None:
        raise LookupError("Pending action was not stored.")
    return row["expires_at"]


def log_tool_call(tool_name: str, arguments: dict, outcome: dict, latency_ms: int) -> None:
    with database_connection() as connection:
        connection.execute(
            "INSERT INTO tool_call_logs (tool_name, arguments, outcome, latency_ms,request_id) "
            "VALUES (%s, %s, %s, %s,%s)",
            (tool_name, Jsonb(json_safe(arguments)), Jsonb(json_safe(outcome)), latency_ms,request_id_context.get()),
        )


def migrate() -> None:
    """Apply additive migrations once under a cross-process lock."""
    ensure_phase2_tables()
    with database_connection() as connection:
        connection.execute("SELECT pg_advisory_xact_lock(309004)")
        connection.execute("CREATE TABLE IF NOT EXISTS schema_migrations (name text PRIMARY KEY, applied_at timestamptz DEFAULT NOW())")
        for path in sorted((Path(__file__).resolve().parent.parent / "db" / "migrations").glob("00[3-5]_*.sql")):
            if connection.execute("SELECT 1 FROM schema_migrations WHERE name=%s", (path.name,)).fetchone():
                continue
            connection.execute(path.read_text(encoding="utf-8"))
            connection.execute("INSERT INTO schema_migrations(name) VALUES (%s)",(path.name,))


def check_database() -> bool:
    """Return whether PostgreSQL accepts a short-lived connection and query."""
    if not DB_PASSWORD:
        return False

    try:
        with database_connection() as connection:
            connection.execute("SELECT 1")
        return True
    except psycopg.Error:
        return False
